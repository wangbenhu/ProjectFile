/*
*********************************************************************************************************
* 函 数 名: myINDLedTest
* 功能说明: 指示灯测试
* 形  参:   无
* 返 回 值: 无
*********************************************************************************************************
*/
void myINDLedTest(void)
{
    static uint32_t SysCnt = 0;
    static bool ledFlag = false;
    uint8_t temp = 0;
    temp = api_GetSysTickCount500ms();
    if (SysCnt != temp)
    {
        SysCnt = temp;

        if (ledFlag == true)
        {
            myINDLed1On();
            // debug_uart_printf("Led1On......\r\n");
            ledFlag = false;
        }
        else
        {
            myINDLed1Off();
            // debug_uart_printf("Led1Off......\r\n");
            ledFlag = true;
        }
    }
}
