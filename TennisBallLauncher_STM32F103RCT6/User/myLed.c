/*
*********************************************************************************************************
* 函 数 名: myINDLed1On
* 功能说明: 指示灯1亮
* 形  参:   无
* 返 回 值: 无
*********************************************************************************************************
*/
void myINDLed1On(void)
{
    HAL_GPIO_WritePin(IND_LED1_GPIO_Port, IND_LED1_Pin, GPIO_PIN_SET);
}
/*
*********************************************************************************************************
* 函 数 名: myINDLed1Off
* 功能说明: 指示灯1灭
* 形  参:   无
* 返 回 值: 无
*********************************************************************************************************
*/
void myINDLed1Off(void)
{
    HAL_GPIO_WritePin(IND_LED1_GPIO_Port, IND_LED1_Pin, GPIO_PIN_RESET);
}
